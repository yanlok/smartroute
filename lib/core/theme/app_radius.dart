/// Centralized border radius tokens extracted from the React SmartRoute application.
class AppRadius {
  AppRadius._();

  /// 4px — very small rounding
  static const double xs = 4.0;

  /// 8px — segment pills, small elements
  static const double sm = 8.0;

  /// 12px — buttons, inputs, icon containers (rounded-xl)
  static const double md = 12.0;

  /// 16px — cards, panels, large buttons (rounded-2xl)
  static const double lg = 16.0;

  /// 20px — dynamic island notch
  static const double xl = 20.0;

  /// 32px — login card top corners (rounded-t-[2rem])
  static const double xxl = 32.0;

  /// Circular — chips, badges, toggles, status dots
  static const double circular = 9999.0;
}
